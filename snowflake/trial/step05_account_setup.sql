-- =====================================================================
-- Step 5: Snowflake account setup for the ShopStream project (trial-friendly)
-- Run in Snowsight as ACCOUNTADMIN. Safe to re-run (IF NOT EXISTS / OR REPLACE).
--
-- Creates:
--   * 3 X-Small warehouses that suspend after 60 seconds idle
--   * a resource monitor that suspends compute before the trial credits run out
--   * 2 databases (RAW_DB, ANALYTICS_DB) with layered schemas
--   * 5 roles in a hierarchy, granted to YOU so you can switch between them
-- =====================================================================

USE ROLE ACCOUNTADMIN;

-- ---------------------------------------------------------------------
-- 1. Warehouses: one per workload, all X-Small (1 credit/hour, billed per second)
-- ---------------------------------------------------------------------
CREATE WAREHOUSE IF NOT EXISTS LOAD_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'COPY INTO / loading';

CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800
  COMMENT = 'dbt transformations';

CREATE WAREHOUSE IF NOT EXISTS BI_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Power BI / analysts';

-- Safety net for the default trial warehouse too
ALTER WAREHOUSE IF EXISTS COMPUTE_WH SET AUTO_SUSPEND = 60;

-- ---------------------------------------------------------------------
-- 2. Resource monitor: protects the trial credits
--    notify at 50% and 80%, suspend all warehouses at 100%
-- ---------------------------------------------------------------------
CREATE OR REPLACE RESOURCE MONITOR RM_SHOPSTREAM_MONTHLY
  WITH CREDIT_QUOTA = 40
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO NOTIFY
           ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND
           ON 110 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE LOAD_WH      SET RESOURCE_MONITOR = RM_SHOPSTREAM_MONTHLY;
ALTER WAREHOUSE TRANSFORM_WH SET RESOURCE_MONITOR = RM_SHOPSTREAM_MONTHLY;
ALTER WAREHOUSE BI_WH        SET RESOURCE_MONITOR = RM_SHOPSTREAM_MONTHLY;

-- ---------------------------------------------------------------------
-- 3. Roles (RBAC hierarchy)
--    SYSADMIN
--      └─ PLATFORM_ADMIN_ROLE
--           ├─ LOADER_ROLE       writes RAW_DB
--           ├─ TRANSFORMER_ROLE  reads RAW_DB, writes ANALYTICS_DB (dbt)
--           │    └─ ANALYST_ROLE
--           │         └─ BI_READER_ROLE   reads MARTS only (Power BI)
--           └─ PII_READER_ROLE   may see unmasked email / phone
-- ---------------------------------------------------------------------
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS PLATFORM_ADMIN_ROLE;
CREATE ROLE IF NOT EXISTS LOADER_ROLE;
CREATE ROLE IF NOT EXISTS TRANSFORMER_ROLE;
CREATE ROLE IF NOT EXISTS ANALYST_ROLE;
CREATE ROLE IF NOT EXISTS BI_READER_ROLE;
CREATE ROLE IF NOT EXISTS PII_READER_ROLE;

GRANT ROLE BI_READER_ROLE   TO ROLE ANALYST_ROLE;
GRANT ROLE ANALYST_ROLE     TO ROLE TRANSFORMER_ROLE;
GRANT ROLE LOADER_ROLE      TO ROLE PLATFORM_ADMIN_ROLE;
GRANT ROLE TRANSFORMER_ROLE TO ROLE PLATFORM_ADMIN_ROLE;
GRANT ROLE PII_READER_ROLE  TO ROLE PLATFORM_ADMIN_ROLE;
GRANT ROLE PLATFORM_ADMIN_ROLE TO ROLE SYSADMIN;

-- Give all of them to you (so you can test each role in Snowsight)
SET ME = CURRENT_USER();
GRANT ROLE PLATFORM_ADMIN_ROLE TO USER IDENTIFIER($ME);
GRANT ROLE LOADER_ROLE         TO USER IDENTIFIER($ME);
GRANT ROLE TRANSFORMER_ROLE    TO USER IDENTIFIER($ME);
GRANT ROLE ANALYST_ROLE        TO USER IDENTIFIER($ME);
GRANT ROLE BI_READER_ROLE      TO USER IDENTIFIER($ME);

-- Warehouse access
GRANT USAGE ON WAREHOUSE LOAD_WH      TO ROLE LOADER_ROLE;
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER_ROLE;
GRANT USAGE ON WAREHOUSE BI_WH        TO ROLE BI_READER_ROLE;
GRANT OPERATE, MONITOR ON WAREHOUSE TRANSFORM_WH TO ROLE PLATFORM_ADMIN_ROLE;

-- ---------------------------------------------------------------------
-- 4. Databases & schemas (bronze / silver / gold)
-- ---------------------------------------------------------------------
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS RAW_DB       DATA_RETENTION_TIME_IN_DAYS = 1 COMMENT = 'Bronze: data as delivered';
CREATE DATABASE IF NOT EXISTS ANALYTICS_DB DATA_RETENTION_TIME_IN_DAYS = 1 COMMENT = 'Silver/Gold: built by dbt';

CREATE SCHEMA IF NOT EXISTS RAW_DB.RAW;
CREATE SCHEMA IF NOT EXISTS RAW_DB.AUDIT;
CREATE TRANSIENT SCHEMA IF NOT EXISTS ANALYTICS_DB.STAGING;       -- no fail-safe storage
CREATE TRANSIENT SCHEMA IF NOT EXISTS ANALYTICS_DB.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS ANALYTICS_DB.MARTS;
CREATE SCHEMA IF NOT EXISTS ANALYTICS_DB.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS ANALYTICS_DB.GOVERNANCE;

-- ---------------------------------------------------------------------
-- 5. Database / schema privileges
-- ---------------------------------------------------------------------
USE ROLE SECURITYADMIN;

-- Loader writes RAW_DB
GRANT USAGE ON DATABASE RAW_DB TO ROLE LOADER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE PIPE, CREATE STREAM
  ON SCHEMA RAW_DB.RAW TO ROLE LOADER_ROLE;
GRANT USAGE, CREATE TABLE ON SCHEMA RAW_DB.AUDIT TO ROLE LOADER_ROLE;

-- Transformer reads RAW_DB (current + future tables)
GRANT USAGE ON DATABASE RAW_DB TO ROLE TRANSFORMER_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RAW_DB TO ROLE TRANSFORMER_ROLE;
GRANT SELECT ON ALL TABLES IN DATABASE RAW_DB TO ROLE TRANSFORMER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW_DB.RAW TO ROLE TRANSFORMER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW_DB.AUDIT TO ROLE TRANSFORMER_ROLE;

-- Transformer owns the ANALYTICS_DB schemas (dbt creates tables/views there)
GRANT USAGE, CREATE SCHEMA ON DATABASE ANALYTICS_DB TO ROLE TRANSFORMER_ROLE;
GRANT OWNERSHIP ON SCHEMA ANALYTICS_DB.STAGING      TO ROLE TRANSFORMER_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ANALYTICS_DB.INTERMEDIATE TO ROLE TRANSFORMER_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ANALYTICS_DB.MARTS        TO ROLE TRANSFORMER_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ANALYTICS_DB.SNAPSHOTS    TO ROLE TRANSFORMER_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ANALYTICS_DB.GOVERNANCE   TO ROLE TRANSFORMER_ROLE COPY CURRENT GRANTS;

-- BI readers: MARTS only (future grants so new dbt tables are visible automatically)
GRANT USAGE ON DATABASE ANALYTICS_DB TO ROLE BI_READER_ROLE;
GRANT USAGE ON SCHEMA ANALYTICS_DB.MARTS TO ROLE BI_READER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS_DB.MARTS TO ROLE BI_READER_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ANALYTICS_DB.MARTS TO ROLE BI_READER_ROLE;

-- ---------------------------------------------------------------------
-- 6. Your defaults, then verify
-- ---------------------------------------------------------------------
USE ROLE ACCOUNTADMIN;
ALTER USER IDENTIFIER($ME) SET DEFAULT_ROLE = PLATFORM_ADMIN_ROLE DEFAULT_WAREHOUSE = TRANSFORM_WH;

SHOW WAREHOUSES LIKE '%_WH';
SHOW RESOURCE MONITORS;
SHOW DATABASES LIKE '%_DB';
SHOW SCHEMAS IN DATABASE ANALYTICS_DB;
SHOW GRANTS TO USER IDENTIFIER($ME);
